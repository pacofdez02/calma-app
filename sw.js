// Service worker mínimo: la app abre sin conexión. Red primero, caché como respaldo.
// Solo toca peticiones GET al propio origen; las llamadas a la API de Claude no pasan por aquí.
const CACHE = 'calma-v1';

self.addEventListener('install', () => self.skipWaiting());
self.addEventListener('activate', (event) => event.waitUntil(self.clients.claim()));

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(request, copy));
        }
        return response;
      })
      .catch(async () => (await caches.match(request)) ?? (await caches.match(self.registration.scope)) ?? Response.error()),
  );
});
